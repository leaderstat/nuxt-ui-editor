test('large file uses bounded virtual DOM and native editing', async ({ page }) => {
  const large = Array.from({ length: 5000 }, (_, i) => `line ${i}`).join('\n')
  await writeFile(join(root, 'source.txt'), large)
  await writeFile(join(root, 'review/001.txt'), large)
  await page.goto('/')
  await page.getByLabel('Workspace directory', { exact: true }).fill(root)
  await page.getByRole('button', { name: 'Open directory', exact: true }).click()
  await expect(page.getByTestId('review-panel').locator('[data-large="true"]')).toBeVisible()
  await page.getByRole('treeitem').filter({ hasText: 'source.txt' }).click()
  await expect(page.getByTestId('review-panel')).toContainText('5000 full')
  expect(await page.getByTestId('review-panel').locator('.virtual-line').count()).toBeLessThan(60)
  await page.getByRole('button', { name: 'Edit text', exact: true }).click()
  await expect(page.getByRole('textbox', { name: 'Review text', exact: true })).toHaveValue(large)
})

test('API rejects foreign origins and missing workspace capabilities', async ({ request }) => {
  const foreign = await request.post('/api/workspace', { data: { action: 'open', root }, headers: { origin: 'https://foreign.example' } })
  expect(foreign.status()).toBe(403)
  const missing = await request.post('/api/workspace', { data: { action: 'load', path: 'source.txt', role: 'source' } })
  expect(missing.status()).toBe(400)
  expect(await missing.text()).toContain('Workspace expired')
})


test('plain-text syntax, spaces and empty lines survive editing and UTF-8 save', async ({ page }) => {
  await open(page)
  const text = '  leading <tag> **literal**\n\ntrailing  \n'
  await page.getByLabel('Review text', { exact: true }).fill(text)
  await page.getByRole('button', { name: 'Save document', exact: true }).click()
  await expect(page.getByText('Unsaved changes', { exact: true })).toHaveCount(0)
  expect(await readFile(join(root, 'review/001.txt'), 'utf8')).toBe(text)
})
