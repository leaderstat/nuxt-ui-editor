import { test, expect, type Page } from '@playwright/test'
import { mkdtemp, mkdir, writeFile, readFile, rm } from 'node:fs/promises'
import { join } from 'node:path'
import { tmpdir } from 'node:os'
let root: string
const source = 'hello!\nAB\nПривет\n\n'
const review = 'AB\nhello?\nunique\nBA\nПривет\n\n'

test.beforeEach(async () => {
  root = await mkdtemp(join(tmpdir(), 'review-browser-'))
  await mkdir(join(root, 'review'))
  await writeFile(join(root, 'source.txt'), source)
  await writeFile(join(root, 'review/001.txt'), review)
  await writeFile(join(root, 'review/002.txt'), 'second\nhello!')
})
test.afterEach(async () => { await rm(root, { recursive: true, force: true }) })
async function open(page: Page) {
  await page.goto('/')
  await page.getByLabel('Workspace directory', { exact: true }).fill(root)
  await page.getByRole('button', { name: 'Open directory', exact: true }).click()
  await expect(page.getByTestId('review-panel')).toBeVisible()
  await page.getByRole('treeitem').filter({ hasText: 'source.txt' }).click()
  await expect(page.getByTestId('source-panel')).toBeVisible()
  const workspace = await page.locator('.workspace-panel').boundingBox()
  const content = await page.locator('.workspace-content').boundingBox()
  expect(content!.width).toBeGreaterThan(workspace!.width * 0.95)
  await expect(page.getByTestId('review-panel').locator('.line-green')).toHaveCount(4)
}
test('offline review, collision protection, delete, undo, redo, save and guarded navigation', async ({ page }) => {
  const errors: string[] = []
  const external: string[] = []
  page.on('pageerror', e => errors.push(e.message))
  await page.route('**/*', route => {
    if (!route.request().url().startsWith('http://127.0.0.1:3000')) { external.push(route.request().url()); return route.abort() }
    return route.continue()
  })
  await open(page)
  await expect(page.getByTestId('review-panel').locator('.line-yellow')).toHaveCount(1)
  await expect(page.getByTestId('review-panel').locator('.line-red')).toHaveCount(2)
  await expect(page.getByLabel('Source text')).toHaveAttribute('contenteditable', 'false')
  const journalBefore = await page.getByRole('region', { name: 'Review journal', exact: true }).boundingBox()
  const handle = await page.getByRole('separator').boundingBox()
  await page.mouse.move(handle!.x + handle!.width / 2, handle!.y + handle!.height / 2)
  await page.mouse.down()
  await page.mouse.move(handle!.x + handle!.width / 2, handle!.y - 70, { steps: 5 })
  await page.mouse.up()
  const journalAfter = await page.getByRole('region', { name: 'Review journal', exact: true }).boundingBox()
  expect(journalAfter!.height).toBeGreaterThan(journalBefore!.height + 40)
  await page.getByRole('button', { name: 'Remove green', exact: true }).click()
  await expect(page.getByLabel('Review text')).toHaveText('hello?uniqueBA')
  expect(await readFile(join(root, 'review/001.txt'), 'utf8')).toBe(review)
  await page.getByRole('button', { name: 'Undo', exact: true }).click()
  await expect(page.getByTestId('review-panel').locator('.line-green')).toHaveCount(4)
  await page.getByRole('button', { name: 'Redo', exact: true }).click()
  await page.getByRole('button', { name: 'Next document', exact: true }).click()
  await expect(page.getByRole('dialog', { name: 'Unsaved document' })).toBeVisible()
  await page.getByRole('button', { name: 'Keep editing', exact: true }).click()
  await expect(page.getByTestId('review-panel')).toContainText('review/001.txt')
  await expect(page.getByRole('dialog', { name: 'Unsaved document' })).toBeHidden()
  await page.getByLabel('Review text', { exact: true }).focus()
  await page.keyboard.press('Control+s')
  await expect(page.getByText('Unsaved changes', { exact: true })).toHaveCount(0)
  expect(await readFile(join(root, 'review/001.txt'), 'utf8')).toBe('hello?\nunique\nBA')
  expect(await readFile(join(root, 'source.txt'), 'utf8')).toBe(source)
  await page.getByRole('button', { name: 'Next document', exact: true }).click()
  await expect(page.getByTestId('review-panel')).toContainText('review/002.txt')
  expect(errors).toEqual([])
  expect(external).toEqual([])
})
test('plain-text editing, filter preview, persistent word filters and discard navigation', async ({ page }) => {
  await open(page)
  const editor = page.getByLabel('Review text', { exact: true })
  await editor.fill('aaa...\nunique')
  await page.getByRole('button', { name: 'Start review', exact: true }).click()
  await expect(page.getByRole('dialog', { name: 'Review filters preview' })).toContainText('a...')
  await page.getByRole('button', { name: 'Apply and analyze', exact: true }).click()
  await expect(editor).toHaveText('a...unique')
  await expect(page.getByRole('dialog', { name: 'Review filters preview' })).toBeHidden()
  await editor.focus()
  await page.keyboard.press('Control+z')
  await expect(editor).toHaveText('aaa...unique')
  await page.getByRole('button', { name: 'Word filters', exact: true }).click()
  await page.getByLabel('New filter words', { exact: true }).fill('unique')
  await page.evaluate(() => {
    window.addEventListener('keydown', e => {
      if (e.ctrlKey && e.key === 'z') document.body.dataset.filterUndoPrevented = String(e.defaultPrevented)
    })
  })
  await page.keyboard.press('Control+z')
  await expect(page.locator('body')).toHaveAttribute('data-filter-undo-prevented', 'false')
  await page.getByLabel('New filter words', { exact: true }).fill('unique')
  await page.getByRole('button', { name: 'Add words', exact: true }).click()
  await page.getByRole('button', { name: 'Save filters', exact: true }).click()
  await expect(page.getByTestId('review-panel').locator('.word-hit')).toHaveCount(1)
  await page.getByRole('button', { name: 'Next document', exact: true }).click()
  await page.getByRole('button', { name: 'Discard changes', exact: true }).click()
  await expect(page.getByTestId('review-panel')).toContainText('review/002.txt')
  expect(await readFile(join(root, 'review/001.txt'), 'utf8')).toBe(review)
  await page.getByLabel('Review text', { exact: true }).fill('saved second')
  await page.getByRole('button', { name: 'Previous document', exact: true }).click()
  await page.getByRole('button', { name: 'Save and continue', exact: true }).click()
  await expect(page.getByTestId('review-panel')).toContainText('review/001.txt')
  expect(await readFile(join(root, 'review/002.txt'), 'utf8')).toBe('saved second')
})
